-- Versioned, reviewed course releases for the React Native learning core.
--
-- Existing Flutter curriculum rows remain untouched. A React Native learner
-- reads only a course explicitly published through this release layer. Draft
-- manifests, unreviewed content, and any exercise with unresolved rights stay
-- unavailable to the client by database policy as well as by app behaviour.

create table if not exists public.course_releases (
    id uuid primary key default gen_random_uuid(),
    course_key text not null
        check (course_key ~ '^[a-z][a-z0-9-]{2,79}$'),
    content_version text not null
        check (content_version ~ '^[0-9]+\.[0-9]+\.[0-9]+(-[a-z0-9.]+)?$'),
    target_language_code text not null
        check (target_language_code ~ '^[a-z]{2,3}(-[A-Z]{2})?$'),
    interface_locale text not null
        check (interface_locale ~ '^[a-z]{2,3}(-[A-Z]{2})?$'),
    title text not null check (char_length(title) between 1 and 160),
    publication_state text not null default 'draft'
        check (publication_state in ('draft', 'published', 'revoked')),
    manifest_checksum text not null
        check (manifest_checksum ~ '^[a-f0-9]{64}$'),
    manifest_uri text not null check (char_length(manifest_uri) between 1 and 500),
    learning_design_approval_ref text,
    native_language_approval_ref text,
    rights_approval_ref text,
    rollback_release_id uuid references public.course_releases(id),
    published_at timestamptz,
    revoked_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (course_key, content_version),
    check (
        publication_state <> 'published'
        or (
            published_at is not null
            and nullif(trim(learning_design_approval_ref), '') is not null
            and nullif(trim(native_language_approval_ref), '') is not null
            and nullif(trim(rights_approval_ref), '') is not null
        )
    ),
    check (publication_state <> 'revoked' or revoked_at is not null)
);

create table if not exists public.course_release_units (
    course_release_id uuid not null references public.course_releases(id) on delete cascade,
    unit_id text not null references public.units(id) on delete restrict,
    order_index integer not null check (order_index >= 0),
    primary key (course_release_id, unit_id),
    unique (course_release_id, order_index)
);

-- Answer material is deliberately stored as reviewed content rather than
-- generated by a client. The server uses it to decide practice completion;
-- the learner's raw response is never persisted by the function below.
create table if not exists public.lesson_exercises (
    id text primary key check (id ~ '^[a-z][a-z0-9_-]{2,79}$'),
    course_release_id uuid not null references public.course_releases(id) on delete cascade,
    lesson_id text not null references public.lessons(id) on delete cascade,
    flashcard_id text references public.flashcards(id) on delete set null,
    order_index integer not null check (order_index >= 0),
    exercise_type text not null
        check (exercise_type in ('recognition', 'typed_recall', 'guided_writing')),
    prompt text not null check (char_length(prompt) between 1 and 600),
    accepted_answers jsonb not null
        check (jsonb_typeof(accepted_answers) = 'array' and jsonb_array_length(accepted_answers) > 0),
    distractors jsonb not null default '[]'::jsonb
        check (jsonb_typeof(distractors) = 'array'),
    hint text not null check (char_length(hint) between 1 and 400),
    remediation text not null check (char_length(remediation) between 1 and 500),
    outcome_refs text[] not null default '{}'::text[]
        check (cardinality(outcome_refs) > 0),
    source_provider text not null check (char_length(source_provider) between 1 and 120),
    source_reference text not null check (char_length(source_reference) between 1 and 240),
    source_licence text not null check (char_length(source_licence) between 1 and 160),
    source_attribution text not null check (char_length(source_attribution) between 1 and 500),
    rights_status text not null check (rights_status in ('pending', 'cleared', 'rejected')),
    learning_design_approval_ref text,
    native_language_approval_ref text,
    rights_approval_ref text,
    is_required boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (course_release_id, lesson_id, order_index),
    check (
        exercise_type <> 'recognition'
        or jsonb_array_length(distractors) >= 2
    )
);

