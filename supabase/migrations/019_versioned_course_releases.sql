-- A release cannot be promoted just by changing a status label. The source
-- approval references, reviewed unit rows, and reviewed exercises must all be
-- in place first. This trigger is intentionally only a release gate; the
-- content JSON contract remains the authoring source of truth.
create or replace function public.assert_course_release_publishable()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    if new.publication_state <> 'published' then
        return new;
    end if;

    if not exists (
        select 1
        from public.course_release_units map
        join public.units unit on unit.id = map.unit_id
        where map.course_release_id = new.id
          and unit.is_reviewed = true
    ) then
        raise exception 'Published course releases require at least one reviewed unit';
    end if;

    if exists (
        select 1
        from public.course_release_units map
        join public.units unit on unit.id = map.unit_id
        where map.course_release_id = new.id
          and unit.is_reviewed = false
    ) then
        raise exception 'Published course releases cannot include unreviewed units';
    end if;

    if not exists (
        select 1 from public.lesson_exercises exercise
        where exercise.course_release_id = new.id
    ) then
        raise exception 'Published course releases require reviewed exercises';
    end if;

    if exists (
        select 1
        from public.course_release_units map
        join public.lessons lesson on lesson.unit_id = map.unit_id
        where map.course_release_id = new.id
          and not exists (
              select 1 from public.lesson_exercises exercise
              where exercise.course_release_id = new.id
                and exercise.lesson_id = lesson.id
          )
    ) then
        raise exception 'Published course releases require reviewed exercises for every mapped lesson';
    end if;

    if exists (
        select 1
        from public.lesson_exercises exercise
        where exercise.course_release_id = new.id
          and not exists (
              select 1
              from public.course_release_units map
              join public.lessons lesson on lesson.unit_id = map.unit_id
              where map.course_release_id = new.id
                and lesson.id = exercise.lesson_id
          )
    ) then
        raise exception 'Published exercises must belong to a lesson mapped into the same release';
    end if;

    if exists (
        select 1 from public.lesson_exercises exercise
        where exercise.course_release_id = new.id
          and (
              exercise.rights_status <> 'cleared'
              or nullif(trim(exercise.learning_design_approval_ref), '') is null
              or nullif(trim(exercise.native_language_approval_ref), '') is null
              or nullif(trim(exercise.rights_approval_ref), '') is null
          )
    ) then
        raise exception 'Published course releases require cleared rights and reviewer evidence for every exercise';
    end if;

    return new;
end;
$$;

drop trigger if exists course_releases_publish_gate on public.course_releases;
create trigger course_releases_publish_gate
before insert or update of publication_state on public.course_releases
for each row execute function public.assert_course_release_publishable();

-- A published release is an evidence record, not a mutable draft. It can only
-- transition to revoked without altering the content identity or approvals.
-- New content requires a new versioned release row.
create or replace function public.prevent_published_course_release_mutation()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    if tg_op = 'DELETE' then
        if old.publication_state in ('published', 'revoked') then
            raise exception 'Published or revoked course releases cannot be deleted';
        end if;
        return old;
    end if;

    if old.publication_state = 'revoked' then
        raise exception 'Revoked course releases cannot be changed';
    end if;

    if old.publication_state = 'published' then
        if new.publication_state <> 'revoked'
           or new.course_key is distinct from old.course_key
           or new.content_version is distinct from old.content_version
           or new.target_language_code is distinct from old.target_language_code
           or new.interface_locale is distinct from old.interface_locale
           or new.title is distinct from old.title
           or new.manifest_checksum is distinct from old.manifest_checksum
           or new.manifest_uri is distinct from old.manifest_uri
           or new.learning_design_approval_ref is distinct from old.learning_design_approval_ref
           or new.native_language_approval_ref is distinct from old.native_language_approval_ref
           or new.rights_approval_ref is distinct from old.rights_approval_ref
           or new.rollback_release_id is distinct from old.rollback_release_id
           or new.published_at is distinct from old.published_at
           or new.revoked_at is null then
            raise exception 'Published course releases may only be revoked without content changes';
        end if;
    end if;

    return new;
end;
$$;

create or replace function public.prevent_published_course_release_membership_mutation()
returns trigger
language plpgsql
set search_path = public
as $$
declare
    v_release_id uuid := case when tg_op = 'DELETE' then old.course_release_id else new.course_release_id end;
begin
    if exists (
        select 1 from public.course_releases release
        where release.id = v_release_id
          and release.publication_state in ('published', 'revoked')
    ) then
        raise exception 'Published or revoked course release membership cannot be changed';
    end if;
    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end;
$$;

