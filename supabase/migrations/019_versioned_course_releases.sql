-- Record a response without persisting its raw text. The server obtains the
-- expected answers from the published release, keeps one active attempt per
-- learner, and returns only the result needed for the UI.
create or replace function public.record_lesson_exercise_response(
    p_lesson_id text,
    p_exercise_id text,
    p_language_code text,
    p_content_version text,
    p_response text
)
returns table (
    is_correct boolean,
    lesson_complete boolean,
    completed_required_exercises integer,
    total_required_exercises integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_user uuid := auth.uid();
    v_release_id uuid;
    v_attempt_id uuid;
    v_expected_answers jsonb;
    v_is_correct boolean;
    v_completed integer;
    v_total integer;
begin
    if v_user is null then
        raise exception 'Authentication required' using errcode = '28000';
    end if;
    if p_response is null or char_length(p_response) > 2000 then
        raise exception 'Invalid practice response' using errcode = '22023';
    end if;

    select release.id
    into v_release_id
    from public.course_releases release
    join public.course_release_units map on map.course_release_id = release.id
    join public.lessons lesson on lesson.unit_id = map.unit_id
    where release.publication_state = 'published'
      and release.revoked_at is null
      and release.target_language_code = p_language_code
      and release.content_version = p_content_version
      and lesson.id = p_lesson_id
    limit 1;

    if v_release_id is null then
        raise exception 'The selected lesson is not in a current published release' using errcode = '22023';
    end if;

    select exercise.accepted_answers
    into v_expected_answers
    from public.lesson_exercises exercise
    where exercise.id = p_exercise_id
      and exercise.course_release_id = v_release_id
      and exercise.lesson_id = p_lesson_id;

    if v_expected_answers is null then
        raise exception 'The selected exercise is not in the published lesson' using errcode = '22023';
    end if;

    select exists (
        select 1
        from jsonb_array_elements_text(v_expected_answers) as answer(value)
        where lower(regexp_replace(trim(answer.value), '[[:space:]]+', ' ', 'g'))
            = lower(regexp_replace(trim(p_response), '[[:space:]]+', ' ', 'g'))
    ) into v_is_correct;

    select attempt.id
    into v_attempt_id
    from public.lesson_attempts attempt
    where attempt.user_id = v_user
      and attempt.course_release_id = v_release_id
      and attempt.lesson_id = p_lesson_id
      and attempt.content_version = p_content_version
      and attempt.completed_at is null
    order by attempt.started_at desc
    limit 1
    for update;

    if v_attempt_id is null then
        insert into public.lesson_attempts
            (user_id, course_release_id, lesson_id, content_version)
        values (v_user, v_release_id, p_lesson_id, p_content_version)
        returning id into v_attempt_id;
    end if;

    insert into public.lesson_exercise_attempts
        (lesson_attempt_id, exercise_id, is_correct)
    values (v_attempt_id, p_exercise_id, v_is_correct)
    on conflict (lesson_attempt_id, exercise_id) do update
    set is_correct = public.lesson_exercise_attempts.is_correct or excluded.is_correct,
        submitted_at = now();

    select count(*) into v_total
    from public.lesson_exercises exercise
    where exercise.course_release_id = v_release_id
      and exercise.lesson_id = p_lesson_id
      and exercise.is_required = true;

    select count(*) into v_completed
    from public.lesson_exercise_attempts attempt
    join public.lesson_exercises exercise on exercise.id = attempt.exercise_id
    where attempt.lesson_attempt_id = v_attempt_id
      and attempt.is_correct = true
      and exercise.is_required = true;

    if v_total > 0 and v_completed >= v_total then
        update public.lesson_attempts
        set completed_at = coalesce(completed_at, now())
        where id = v_attempt_id;
    end if;

    return query select v_is_correct, v_total > 0 and v_completed >= v_total, v_completed, v_total;
end;
$$;

-- Record completion only after the server has a completed exercise attempt in
-- the exact current course version. This is additive so the Flutter fallback
-- keeps using its existing completion RPC until it is migrated deliberately.
create or replace function public.complete_published_lesson(
    p_lesson_id text,
    p_language_code text,
    p_content_version text
)
returns table (attempts integer)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_user uuid := auth.uid();
    v_release_id uuid;
    v_attempts integer;
begin
    if v_user is null then
        raise exception 'Authentication required' using errcode = '28000';
    end if;

    select release.id
    into v_release_id
    from public.course_releases release
    join public.course_release_units map on map.course_release_id = release.id
    join public.lessons lesson on lesson.unit_id = map.unit_id
    where release.publication_state = 'published'
      and release.revoked_at is null
      and release.target_language_code = p_language_code
      and release.content_version = p_content_version
      and lesson.id = p_lesson_id
    limit 1;

    if v_release_id is null or not exists (
        select 1 from public.lesson_attempts attempt
        where attempt.user_id = v_user
          and attempt.course_release_id = v_release_id
          and attempt.lesson_id = p_lesson_id
          and attempt.content_version = p_content_version
          and attempt.completed_at is not null
    ) then
        raise exception 'Complete each required published exercise before recording this lesson' using errcode = '22023';
    end if;

    insert into public.lesson_progress (user_id, lesson_id, language_code)
    values (v_user, p_lesson_id, p_language_code)
    on conflict (user_id, lesson_id) do update
    set attempts = public.lesson_progress.attempts + 1,
        last_completed_at = now()
    returning lesson_progress.attempts into v_attempts;

    return query select v_attempts;
end;
$$;

-- SRS scheduling is server-authoritative for published release cards. The
-- learner supplies a rating, but cannot write intervals, repetitions, or due
-- timestamps directly through this RN contract.
create or replace function public.record_card_review(
    p_card_id text,
    p_language_code text,
    p_rating text
)
returns table (
    next_review_at timestamptz,
    interval_days integer,
    repetitions integer,
    efactor numeric
)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_user uuid := auth.uid();
    v_interval integer := 0;
    v_repetitions integer := 0;
    v_efactor numeric := 2.50;
    v_next_review_at timestamptz;
begin
    if v_user is null then
        raise exception 'Authentication required' using errcode = '28000';
    end if;
    if p_rating not in ('again', 'hard', 'good', 'easy') then
        raise exception 'Invalid review rating' using errcode = '22023';
    end if;
    if not exists (
        select 1
        from public.course_releases release
        join public.course_release_units map on map.course_release_id = release.id
        join public.lessons lesson on lesson.unit_id = map.unit_id
        join public.flashcards card on card.lesson_id = lesson.id
        where release.publication_state = 'published'
          and release.revoked_at is null
          and release.target_language_code = p_language_code
          and card.id = p_card_id
    ) then
        raise exception 'The selected card is not in a current published release' using errcode = '22023';
    end if;

    select review.interval, review.repetitions, review.efactor
    into v_interval, v_repetitions, v_efactor
    from public.card_reviews review
    where review.user_id = v_user
      and review.card_id = p_card_id
      and review.language_key = p_language_code
    for update;

    v_interval := coalesce(v_interval, 0);
    v_repetitions := coalesce(v_repetitions, 0);
    v_efactor := coalesce(v_efactor, 2.50);

    if p_rating = 'again' then
        v_repetitions := 0;
        v_interval := 0;
        v_efactor := greatest(1.30, v_efactor - 0.20);
        v_next_review_at := now() + interval '10 minutes';
    else
        v_repetitions := v_repetitions + 1;
        v_efactor := least(
            2.80,
            greatest(1.30, v_efactor + case p_rating when 'hard' then -0.15 when 'easy' then 0.15 else 0 end)
        );
        if v_repetitions = 1 then
            v_interval := case p_rating when 'hard' then 1 when 'easy' then 2 else 1 end;
        elsif v_repetitions = 2 then
            v_interval := case p_rating when 'hard' then 2 when 'easy' then 5 else 3 end;
        else
            v_interval := greatest(
                1,
                ceil(v_interval * (v_efactor + case p_rating when 'hard' then -0.15 when 'easy' then 0.15 else 0 end))::integer
            );
        end if;
        v_next_review_at := now() + make_interval(days => v_interval);
    end if;

    insert into public.card_reviews
        (user_id, card_id, language_key, interval, repetitions, efactor, next_review_at)
    values (v_user, p_card_id, p_language_code, v_interval, v_repetitions, v_efactor, v_next_review_at)
    on conflict (user_id, card_id, language_key) do update
    set interval = excluded.interval,
        repetitions = excluded.repetitions,
        efactor = excluded.efactor,
        next_review_at = excluded.next_review_at,
        updated_at = now();

    return query select v_next_review_at, v_interval, v_repetitions, v_efactor;
end;
$$;

